    def _build_qr_code(self, audit_hash: str) -> Any:
        """Generate a QR code for the audit trail."""
        from reportlab.platypus import Image
        qr = qrcode.QRCode(
            version=1,
            error_correction=qrcode.constants.ERROR_CORRECT_L,
            box_size=10,
            border=4,
        )
        qr.add_data(audit_hash)
        qr.make(fit=True)
        img = qr.make_image(fill_color="black", back_color="white")
        
        img_byte_arr = io.BytesIO()
        img.save(img_byte_arr, format='PNG')
        img_byte_arr.seek(0)
        
        return Image(img_byte_arr, width=2*inch, height=2*inch)

    def _add_watermark(self, canvas, doc):
        """Draw diagonal watermark."""
        canvas.saveState()
        canvas.setFont('Helvetica-Bold', 40)
        canvas.setStrokeColorRGB(0.5, 0.5, 0.5)
        canvas.setFillColorRGB(0.5, 0.5, 0.5)
        canvas.setFillAlpha(0.2)
        
        # Translate to center of page
        canvas.translate(A4[0]/2, A4[1]/2)
        canvas.rotate(45)
        
        text = f"SENTINEL - CONFIDENTIAL - {datetime.now().strftime('%Y-%m-%d')}"
        canvas.drawCentredString(0, 0, text)
        canvas.restoreState()

