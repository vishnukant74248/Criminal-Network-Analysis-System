class DossierGenerator:
    """Generates PDF dossiers for suspects with network analysis and evidence."""
    
    def __init__(self):
        self.styles = getSampleStyleSheet()
        self.styles.add(ParagraphStyle(
            name='CenterTitle',
            parent=self.styles['Heading1'],
            alignment=TA_CENTER,
            textColor=colors.HexColor('#e63946'),
            fontSize=24
        ))
        self.styles.add(ParagraphStyle(
            name='Confidential',
            parent=self.styles['Normal'],
            alignment=TA_CENTER,
            textColor=colors.red,
            fontSize=14,
            fontName='Helvetica-Bold'
        ))

    def generate(self, suspect_data: Dict, graph_data: Dict, centrality_data: Dict, evidence_list: List, output_path: str) -> str:
        """
        Creates complete PDF dossier. Returns path to generated PDF.
        """
        doc = SimpleDocTemplate(
            output_path,
            pagesize=A4,
            rightMargin=inch,
            leftMargin=inch,
            topMargin=inch,
            bottomMargin=inch
        )
        
        story = []
        
        self._build_cover_page(story, self.styles, suspect_data)
        story.append(PageBreak())
        
        self._build_suspect_card(story, self.styles, suspect_data)
        story.append(Spacer(1, 0.5 * inch))
        
        self._build_centrality_table(story, self.styles, centrality_data)
        story.append(Spacer(1, 0.5 * inch))
        
        self._build_network_summary(story, self.styles, graph_data)
        story.append(Spacer(1, 0.5 * inch))
        
        self._build_evidence_list(story, self.styles, evidence_list)
        
        doc.build(story, onFirstPage=self._add_watermark, onLaterPages=self._add_watermark)
        return output_path

    def _build_cover_page(self, story: List, styles: Any, suspect_data: Dict) -> None:
        """Add SENTINEL branding header and classification banner."""
        story.append(Paragraph("CONFIDENTIAL", styles['Confidential']))
        story.append(Spacer(1, 2 * inch))
        story.append(Paragraph("SENTINEL", styles['CenterTitle']))
        story.append(Paragraph("AI-Powered Criminal Network Analysis System", styles['Title']))
        story.append(Spacer(1, 1 * inch))
        story.append(Paragraph("TARGET DOSSIER", styles['Heading2']))
        story.append(Spacer(1, 0.5 * inch))
        
        data = [
            ["Case Number:", f"SENTINEL-{datetime.now().strftime('%Y%m%d')}-{suspect_data.get('id', 'UNK')}"],
            ["Target Name:", suspect_data.get("name", "Unknown")],
            ["Date Generated:", datetime.now().strftime("%Y-%m-%d %H:%M:%S")],
            ["Generated By:", "System Administrator"]
        ]
        
        table = Table(data, colWidths=[2 * inch, 4 * inch])
        table.setStyle(TableStyle([
            ('BACKGROUND', (0, 0), (0, -1), colors.HexColor('#2a2a2a')),
            ('TEXTCOLOR', (0, 0), (0, -1), colors.whitesmoke),
            ('ALIGN', (0, 0), (-1, -1), 'LEFT'),
            ('FONTNAME', (0, 0), (0, -1), 'Helvetica-Bold'),
            ('BOTTOMPADDING', (0, 0), (-1, -1), 12),
            ('BACKGROUND', (1, 0), (1, -1), colors.HexColor('#1a1a1a')),
            ('TEXTCOLOR', (1, 0), (1, -1), colors.lightgrey),
            ('GRID', (0, 0), (-1, -1), 1, colors.black)
        ]))
        story.append(table)
        story.append(Spacer(1, 2 * inch))
        
        audit_hash = f"hash-{suspect_data.get('id', 'UNK')}-{datetime.now().timestamp()}"
